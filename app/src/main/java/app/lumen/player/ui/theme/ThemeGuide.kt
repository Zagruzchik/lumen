=== ГДЕ ПРИМЕНЯЕТСЯ КАЖДЫЙ ТОКЕН (чтобы понимать последствия) ===
- background: фон под всем; на AMOLED-экранах "#000000" = пиксели выключены (максимальная экономия).
- text / textDim / textFaint: все надписи. textDim и textFaint обычно = text с прозрачностью 70% и 50%.
- accent: кнопка «Слушать», «Обновить», включённые переключатели, ползунки, текущий трек в списках, подсветка
  выбранной категории в библиотеке, галочки. При accentMode = "cover" поле accent игнорируется.
- onAccent: текст на акцентных кнопках-пилюлях.
- card / cardStrong / border: карточки настроек, кнопки-пилюли («Перемешать», «Импорт»), поля ввода, плитки.
- sheetTop / sheetBottom: все нижние шторки и всплывающие окна (меню трека, «В плейлист», информация,
  обновление, теги, выбор цвета, нижняя панель категорий в библиотеке, уведомление «Добавлено»).
  Делай их почти непрозрачными (E6–FF), иначе текст под шторкой будет мешать читать.
- panelTint + blur + noise: мини-плеер и нижняя навигация (настоящее размытие того, что под ними).
- backdrop.*: фон главной, библиотеки, настроек (то, что «просвечивает» сквозь стекло).
- playerMode / playerDim: фон развёрнутого плеера.
- effects.*: декоративные анимации. Выключенные эффекты не только не рисуются, но и не тратят кадры.

=== ПРАВИЛА КАЧЕСТВА ===
1. Контраст: text на background — не менее 7:1; textDim — не менее 4.5:1; onAccent на accent — не менее 4.5:1.
2. Стеклянные поверхности (card, cardStrong, border) делай полупрозрачными оттенками белого или цвета темы
   (5–30% непрозрачности), иначе пропадёт эффект стекла.
3. sheetTop/sheetBottom — почти непрозрачные (E6–FF).
4. Энергосбережение: background "#000000", backdrop.mode "solid", playerMode "solid", blur 0,
   все effects false, motion 0, panelTint почти непрозрачный.
5. Полный глассморфизм: backdrop.mode "cover", strength 0.85–1, blur 36–48, card 20–30% белого,
   border 30–45% белого, highlight 1, sheets с прозрачностью B3–CC.
6. Неон/яркие темы: accentMode "fixed", насыщенный accent, border = accent на 40–60%, backdrop "gradient"
   из 2–3 неоновых цветов, background очень тёмный с оттенком (например "#07041A").
7. Светлая тема: background светлый ("#F4F2F8"), text тёмный ("#15121B"), textDim "#B315121B", textFaint "#8015121B",
   card "#14000000", border "#1F000000", sheets светлые ("#F7FFFFFF"/"#FFF4F2F8"), panelTint "#CCFFFFFF",
   backdrop strength 0.3–0.4. ВНИМАНИЕ: часть декоративных элементов (размытая обложка в плеере, белые волны и
   белые кнопки воспроизведения) рассчитана на тёмный фон — для светлой темы ставь playerDim повыше (0.7+).
8. Не придумывай новых полей — неизвестные поля игнорируются. Числа — обычные числа (не строки).
9. Значения вне диапазонов обрезаются: blur 0..80, highlight 0..1, noise 0..0.3, strength/playerDim/motion 0..1.
10. Отдавай только валидный JSON без комментариев (комментарии выше — только для пояснения).

